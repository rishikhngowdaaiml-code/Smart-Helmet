class CameraStream:
    """Dedicated background thread for reading frames to eliminate buffer lag (<0.1s delay)"""
    def __init__(self, src):
        self.src = src
        self.cap = None
        self.ret, self.frame = False, None
        self.frame_id = 0
        self.running = True
        
        # Start thread immediately. Hardware initialization happens inside the thread.
        self.thread = threading.Thread(target=self.update, daemon=True)
        self.thread.start()

    def update(self):
        # 1. Open camera precisely in the thread that reads it (Fixes Windows COM black screens)
        # Using a lock to ensure Windows USB Bus doesn't crash when opening multiple cameras
        with camera_init_lock:
            # Attempt to use DirectShow backend for faster startup
            self.cap = cv2.VideoCapture(self.src, cv2.CAP_DSHOW)
            if not self.cap.isOpened():
                print(f"Warning: CAP_DSHOW failed for camera {self.src}. Falling back to default MSMF backend.")
                self.cap = cv2.VideoCapture(self.src)
            
            # 2. CRITICAL: Force OpenCV to NOT buffer old frames. This guarantees < 0.1s delay!
            # We do NOT force hardware width/height here anymore as it breaks some USB cameras.
            self.cap.set(cv2.CAP_PROP_BUFFERSIZE, 1)
        
        while self.running:
            if self.cap and self.cap.isOpened():
                # Continuously grab frames as fast as hardware allows to clear any buffers
                ret, frame = self.cap.read()
                if ret:
                    self.ret, self.frame = ret, frame
                    self.frame_id += 1
                else:
                    time.sleep(0.01) # Prevent 100% CPU pinning if the camera glitches
                    
    def isOpened(self):
        return self.cap is not None and self.cap.isOpened()

    def read(self):
        return self.ret, self.frame

    def release(self):
        self.running = False
        if self.cap and self.cap.isOpened():
            self.cap.release()

def run_ai_inference(frame, detector, plate_reader, stabilizer):
    global latest_detections, latest_violations, ai_thread_running, violations_db, last_violation_time
    
    try:
        detections = []
        # Module 1: Stabilize the frame
        stabilized_frame = stabilizer.stabilize(frame)
        
        # Module 3 & 7: Adaptive Frame Selection (Get the best frame in the buffer)
        best_frame, best_score, is_blurry = stabilizer.adaptive_frame_selection(stabilized_frame)
        
        # Module 2: Blur Detection - skip highly blurred frames to save computation
        if is_blurry:
            # We skip AI processing on this frame because it's too blurry
            # But we still update the global state with the stabilized frame so the frontend stays smooth
            with frame_lock:
                pass
            ai_thread_running = False
            return
            
        # Run YOLOv8 on this background thread using the best frame from the temporal window
        _, violations, detections = detector.process_frame(best_frame)
        
        # Safely update the shared tracking state
        with lock:
            latest_detections = detections
            latest_violations = violations
            
        # OCR and Database Insertion Logic
        current_time = time.time()
        if len(violations) > 0 and (current_time - last_violation_time > 10.0):
            last_violation_time = current_time
            v = violations[0] # Process the most prominent violation
            box = v["bbox"]
            track_id = v.get("id", -1)
            
            # Module 5: If we already have the plate for this track ID, skip heavy OCR!
            if track_id != -1 and track_id in active_tracked_plates:
                plate_text, ocr_conf = active_tracked_plates[track_id]
            else:
                # Find the motorcycle bounding box to crop
                mc_box = None
                for d in detections:
                    if (d["name"] == "motorcycle" or d["name"] == "3") and d.get("id") == track_id:
                        mc_box = d["bbox"]
                        break
                
                # Fallback to the violation bounding box if motorcycle box isn't found
                if mc_box is None:
                    mc_box = v["bbox"]
                    
                mc_crop = best_frame[max(0, int(mc_box[1])):int(mc_box[3]), max(0, int(mc_box[0])):int(mc_box[2])]
                
                # Module 8 & 4 & 5: Enhanced Plate Reading on the cropped frame
                plate_text, ocr_conf = plate_reader.extract_text(mc_crop)
                
                if plate_text and track_id != -1:
                    # Save it in active tracking so we don't re-run OCR next frame
                    active_tracked_plates[track_id] = (plate_text, ocr_conf)
            
            if not plate_text:
                plate_text = "UNKNOWN"
                ocr_conf = 0.0
                
            # Module 2: Check Duplicate Engine
            if dup_engine.is_duplicate(plate_text):
                # We skip inserting into the database to prevent duplicate spam!
                # But we can still update the UI.
                ai_thread_running = False
                return
                
            new_record = {
                "plate_number": plate_text,
                "type": v.get("type", "UNKNOWN_VIOLATION"),
                "timestamp": datetime.now().isoformat(),
                "gps_latitude": 12.9716, # Placeholder
                "gps_longitude": 77.5946, # Placeholder
                "device_id": "HELMET-001",
                "detection_confidence": v["conf"],
                "ocr_confidence": ocr_conf
            }
            
            # Insert into robust SQLite database
            violation_id = db.insert_violation(new_record)
            
            # Save the frozen snapshot frame to disk
            snapshot_path = os.path.join("snapshots", f"{violation_id}.jpg")
            
            # Geotag overlay logic using the BEST frame
            snapshot_frame = best_frame.copy()
            
            # --- GEO-TAG OVERLAY ---
            overlay = snapshot_frame.copy()
            h_img, w_img, _ = snapshot_frame.shape
            
            rect_h = 130
            cv2.rectangle(overlay, (0, h_img - rect_h), (w_img, h_img), (0, 0, 0), -1)
            cv2.addWeighted(overlay, 0.6, snapshot_frame, 0.4, 0, snapshot_frame)
            
            now = datetime.now()
            date_str = now.strftime("%A, %d/%m/%Y %I:%M %p GMT +05:30")
            lat_lng = "Lat 12.921686° Long 77.542179°"
            location_details = "22, 21st Cross Rd, Ittamadu, Banashankari 3rd Stage, Banashankari, Bengaluru, Karnataka 560085, India"
            city_state = "Bengaluru, Karnataka, India"
            
            font = cv2.FONT_HERSHEY_SIMPLEX
            cv2.putText(snapshot_frame, city_state, (20, h_img - 95), font, 0.8, (255, 255, 255), 2)
            cv2.putText(snapshot_frame, location_details, (20, h_img - 65), font, 0.5, (230, 230, 230), 1)
            cv2.putText(snapshot_frame, lat_lng, (20, h_img - 40), font, 0.5, (230, 230, 230), 1)
            cv2.putText(snapshot_frame, date_str, (20, h_img - 15), font, 0.5, (230, 230, 230), 1)
            
            cv2.imwrite(snapshot_path, snapshot_frame)
            
            # Fire off the automated email in the background
            threading.Thread(target=send_automated_email, args=(new_record, snapshot_path)).start()
            
            print(f"🚨 ALERT: Logged {new_record['type']} | Plate: {new_record['plate_number']}")
    finally:
        # Clean up old active tracked plates that left the frame
        current_ids = [d.get("id") for d in detections if d.get("id") is not None]
        keys_to_remove = [k for k in active_tracked_plates.keys() if k not in current_ids]
        for k in keys_to_remove:
            del active_tracked_plates[k]

        # Signal that the AI thread is free to accept a new frame!
        ai_thread_running = False

def detection_loop(cap, detector, plate_reader, stabilizer, buffer):
    global global_frame, violations_db, last_violation_time, ai_thread_running, latest_detections, latest_violations, new_frame_event
    print("Starting Smart Helmet Edge Node USB Camera...")
    
    print("Camera hardware requested. Streaming raw feed and applying YOLOv8 inference...")

    last_frame_id = -1

    while True:
        # Throttle loop to match camera FPS (~30 FPS)
        time.sleep(1/30.0)
            
        last_frame_id = cap.frame_id if cap and cap.isOpened() else last_frame_id
        
        frames_to_stitch = []
        
        # Read Camera
        if cap and cap.isOpened():
            ret, frame = cap.read()
            if ret:
                frame = cv2.resize(frame, (640, 480))
                cv2.putText(frame, "LAPTOP CAM", (15, 35), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0, 255, 255), 2)
                frames_to_stitch.append(frame)
                
        if not frames_to_stitch:
            # If cameras are opened but haven't yielded a frame yet, push a placeholder frame
            dummy_frame = np.zeros((480, 640, 3), dtype=np.uint8)
            cv2.putText(dummy_frame, "CONNECTING TO HARDWARE...", (50, 240), cv2.FONT_HERSHEY_SIMPLEX, 1, (255, 255, 255), 2)
            with lock:
                global_frame = dummy_frame
            time.sleep(0.01)
            continue
            
        # Stitch frames - ALWAYS perfectly 640x480
        combined_frame = frames_to_stitch[0]
            
        annotated_frame = combined_frame.copy()
        
        # Run AI Asynchronously! This guarantees perfectly smooth 30 FPS video with NO DELAY!
        if detector and plate_reader and buffer:
            buffer.add_frame(combined_frame)
            
            # Fire and forget YOLO inference in background if it's not busy
            if not ai_thread_running:
                ai_thread_running = True
                threading.Thread(target=run_ai_inference, args=(combined_frame.copy(), detector, plate_reader, stabilizer), daemon=True).start()
                
            # Instantly draw the latest known bounding boxes on the raw real-time frame!
            with lock:
                motorcycles = [d for d in latest_detections if d["name"] in ["motorcycle", "3"]]
                people = [d for d in latest_detections if d["name"] in ["person", "0"]]
                
                for mc in motorcycles:
                    mc_box = mc["bbox"]
                    cv2.rectangle(annotated_frame, (int(mc_box[0]), int(mc_box[1])), (int(mc_box[2]), int(mc_box[3])), (255, 0, 0), 2)
                    cv2.putText(annotated_frame, "Motorcycle", (int(mc_box[0]), int(mc_box[1])-10), cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255,0,0), 2)
                    
                for p in people:
                    p_box = p["bbox"]
                    # If the person is part of a violation, we draw them red, otherwise green
                    is_violating = any(v["type"] == "NO_HELMET" and v["bbox"] == p_box for v in latest_violations)
                    color = (0, 0, 255) if is_violating else (0, 255, 0)
                    cv2.rectangle(annotated_frame, (int(p_box[0]), int(p_box[1])), (int(p_box[2]), int(p_box[3])), color, 2)
                    
                for v in latest_violations:
                    box = v["bbox"]
                    cv2.putText(annotated_frame, f"VIOLATION: {v['type']}", (int(box[0]), int(box[1])-30), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0,0,255), 2)
        else:
            # AI is still loading, just stream the raw camera feed with a warning
            cv2.putText(annotated_frame, "AI WARMING UP...", (15, 80), cv2.FONT_HERSHEY_SIMPLEX, 1, (0, 165, 255), 2)
        
        # Safely update the global frame for the web stream
        with lock:
            global_frame = annotated_frame.copy()
            
        # Instantly notify the Flask server to stream the new frame to the browser!
        new_frame_event.set()
        new_frame_event.clear()

def generate_frames():
    global global_frame, new_frame_event
    while True:
        # Wait directly on the OS level for a new frame, 0ms CPU overhead, 0 lag!
        new_frame_event.wait(timeout=0.1)
        
        with lock:
            if global_frame is None:
                continue
            # Encode frame as JPEG
            ret, buffer = cv2.imencode('.jpg', global_frame, [int(cv2.IMWRITE_JPEG_QUALITY), 80])
            if not ret:
                continue
            frame_bytes = buffer.tobytes()
            
        yield (b'--frame\r\n'
               b'Content-Type: image/jpeg\r\n\r\n' + frame_bytes + b'\r\n')

@app.route('/video_feed')
def video_feed():
    return Response(generate_frames(), mimetype='multipart/x-mixed-replace; boundary=frame')

